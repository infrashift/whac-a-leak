package rules

import (
	"bytes"
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"cuelang.org/go/cue"
	"cuelang.org/go/cue/build"
	"cuelang.org/go/cue/cuecontext"
	cueerrors "cuelang.org/go/cue/errors"
	"cuelang.org/go/cue/parser"
)

//go:embed builtin/*.cue
var builtinFS embed.FS

const (
	builtinDir = "builtin"
	schemaFile = "schema.cue"
	// builtinPrefix names embedded files in CUE error positions.
	builtinPrefix = "(builtin)/"
)

// GeneratedHeader starts the schema copy written by `whac rules export-schema`.
// Files that start with it are skipped by the loader: they exist for editors
// and `cue vet`, and a stale copy must never conflict with the embedded schema.
const GeneratedHeader = "// Code generated by whac rules export-schema. DO NOT EDIT."

// topLevelFields are the only regular fields a layer may set.
var topLevelFields = []string{"allowlist", "config", "overrides", "rules"}

// Options controls where user layers come from.
type Options struct {
	// ConfigDir holds user layers (*.cue, package whac). Empty means none.
	ConfigDir string
	// RequireConfigDir makes a missing ConfigDir an error instead of
	// meaning "no user layers".
	RequireConfigDir bool
}

// LoadError is a CUE evaluation error with every position reported.
type LoadError struct {
	Details string
}

func (e *LoadError) Error() string {
	return "invalid rule configuration:\n" + strings.TrimRight(e.Details, "\n")
}

// SchemaSource returns the embedded schema, for `whac rules export-schema`.
func SchemaSource() []byte {
	b, err := builtinFS.ReadFile(path.Join(builtinDir, schemaFile))
	if err != nil {
		panic(fmt.Sprintf("embedded schema missing: %v", err)) // a build defect, not a runtime condition
	}
	return b
}

type source struct {
	name string
	data []byte
}

// Load unifies the embedded schema and builtin rules with the user layers,
// validates the result, and compiles every rule. It does not run the rules'
// own tests; callers pair it with engine.Verify (ADR-0009).
func Load(opts Options) (*Ruleset, error) {
	srcs, err := builtinSources()
	if err != nil {
		return nil, err
	}
	layers, err := userSources(opts)
	if err != nil {
		return nil, err
	}
	srcs = append(srcs, layers...)

	v, err := evaluate(srcs)
	if err != nil {
		return nil, err
	}
	var doc document
	if decodeErr := v.Decode(&doc); decodeErr != nil {
		return nil, &LoadError{Details: cueerrors.Details(decodeErr, nil)}
	}
	rs, err := compile(&doc)
	if err != nil {
		return nil, err
	}
	for _, l := range layers {
		rs.Layers = append(rs.Layers, l.name)
	}
	return rs, nil
}

func builtinSources() ([]source, error) {
	entries, err := fs.ReadDir(builtinFS, builtinDir)
	if err != nil {
		return nil, fmt.Errorf("reading embedded rules: %w", err)
	}
	srcs := make([]source, 0, len(entries))
	for _, e := range entries {
		data, err := builtinFS.ReadFile(path.Join(builtinDir, e.Name()))
		if err != nil {
			return nil, fmt.Errorf("reading embedded rules: %w", err)
		}
		srcs = append(srcs, source{name: builtinPrefix + e.Name(), data: data})
	}
	return srcs, nil
}

func userSources(opts Options) ([]source, error) {
	if opts.ConfigDir == "" {
		return nil, nil
	}
	info, err := os.Stat(opts.ConfigDir)
	switch {
	case errors.Is(err, fs.ErrNotExist) && !opts.RequireConfigDir:
		return nil, nil
	case err != nil:
		return nil, fmt.Errorf("config dir: %w", err)
	case !info.IsDir():
		return nil, fmt.Errorf("config dir %s is not a directory", opts.ConfigDir)
	}

	dir := os.DirFS(opts.ConfigDir)
	names, err := fs.Glob(dir, "*.cue")
	if err != nil {
		return nil, fmt.Errorf("config dir: %w", err)
	}
	slices.Sort(names)
	var srcs []source
	for _, name := range names {
		data, err := fs.ReadFile(dir, name)
		if err != nil {
			return nil, fmt.Errorf("config dir: %w", err)
		}
		if bytes.HasPrefix(data, []byte(GeneratedHeader)) {
			continue
		}
		srcs = append(srcs, source{name: filepath.Join(opts.ConfigDir, name), data: data})
	}
	return srcs, nil
}

// evaluate builds every source as one in-memory CUE package instance
// (ADR-0012), so layers can reference the schema's definitions without a
// cue.mod or files on disk.
func evaluate(srcs []source) (cue.Value, error) {
	inst := build.NewContext().NewInstance("", nil)
	for _, s := range srcs {
		f, err := parser.ParseFile(s.name, s.data, parser.ParseComments)
		if err != nil {
			return cue.Value{}, &LoadError{Details: cueerrors.Details(err, nil)}
		}
		if err := inst.AddSyntax(f); err != nil {
			return cue.Value{}, &LoadError{Details: cueerrors.Details(err, nil)}
		}
	}
	if inst.Err != nil {
		return cue.Value{}, &LoadError{Details: cueerrors.Details(inst.Err, nil)}
	}
	v := cuecontext.New().BuildInstance(inst)
	if err := v.Err(); err != nil {
		return cue.Value{}, &LoadError{Details: cueerrors.Details(err, nil)}
	}
	if err := checkTopLevel(v); err != nil {
		return cue.Value{}, err
	}
	if err := v.Validate(cue.Concrete(true)); err != nil {
		return cue.Value{}, &LoadError{Details: cueerrors.Details(err, nil)}
	}
	return v, nil
}

// checkTopLevel rejects misspelt top-level fields such as `rule:`, which CUE
// would otherwise accept silently because package scope is open.
func checkTopLevel(v cue.Value) error {
	it, err := v.Fields()
	if err != nil {
		return &LoadError{Details: cueerrors.Details(err, nil)}
	}
	var unknown []string
	for it.Next() {
		name := it.Selector().String()
		if !slices.Contains(topLevelFields, name) {
			pos := it.Value().Pos()
			unknown = append(unknown, fmt.Sprintf("%s: unknown top-level field (want one of %s):\n    %s",
				name, strings.Join(topLevelFields, ", "), pos))
		}
	}
	if len(unknown) > 0 {
		return &LoadError{Details: strings.Join(unknown, "\n")}
	}
	return nil
}
